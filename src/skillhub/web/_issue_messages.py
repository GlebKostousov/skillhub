type IssueText = tuple[str | None, str, str]


def issue_text(issue: LoadIssue) -> IssueText:
    """Возвращает безопасный идентификатор, объяснение и действие."""
    if issue.path == ".":
        message, action = _ROOT_ISSUE_TEXT.get(
            issue.reason,
            (
                "Каталог не удалось загрузить.",
                "Проверьте настроенную папку skills и повторите перезагрузку.",
            ),
        )
        return None, message, action
    message, action = _SKILL_ISSUE_TEXT.get(
        issue.reason,
        (
            "Не удалось загрузить режим «{path}».",
            "Проверьте структуру его файла SKILL.md и повторите перезагрузку.",
        ),
    )
    return (
        issue.path,
        message.format(path=issue.path),
        action.format(path=issue.path),
    )
